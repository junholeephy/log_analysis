"""배포마다 바뀌는 값을 한 곳에 모은다.

이 파일만 열어 보면 "다른 장비로 옮길 때 무엇을 고쳐야 하는가"가 끝난다.
전에는 서비스 오류 문구는 checks.py, 히스토리 턴 수는 conv.py, 조직 필드 후보는
org.py, 환경변수 이름은 backends.py 에 흩어져 있었다. 옮기는 사람이 그걸
전부 찾아다녀야 했다.

여기 없는 것도 바뀔 수 있다. 크기가 커서 원래 자리에 둔 것들이다:
    ragdiag/prompts.py    LLM 시스템 프롬프트 4종
    ragdiag/taxonomy.py   케이스 29개와 설명
    ragdiag/labels.py     query · emotion 라벨표 (운영 장비에는 그쪽 것이 있다)

**여기 값을 바꾸면 골든셋·회귀셋을 다시 돌릴 것.** 임계값 하나가 판정 전체를
움직인다. 특히 MATCH_THRESHOLD 를 낮추면 지어낸 인용이 통과하기 시작한다.
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# 서비스 자원 부족 응답  (case9)
#
# 모델 자원을 확보하지 못했을 때 서비스 계층이 답변 자리에 넣는 확정 문구.
# LLM 이 만든 답이 아니므로 코드로 대조한다. 배포마다 다르니 줄을 추가해 쓴다.
# 부분 일치라 뒤에 안내가 더 붙어도 잡힌다 - 앞부분만 정확하면 된다.
# ---------------------------------------------------------------------------

SERVICE_ERROR_TEMPLATES = (
    "서비스에 문제가 있거나, 사용자 분들이 많아서 서버에 부하가 걸리고 있어요",
)

# 확정 문구가 조금 바뀌어도 놓치지 않게 두는 보조 표지. 단독으로는 쓰지 않고
# 두 개 이상 겹칠 때만 인정한다 - "서버" 한 단어로 잡으면 서버 관련 질문에
# 정상적으로 답한 것까지 오탐한다.
SERVICE_ERROR_MARKERS = (
    "서버에 부하", "사용자 분들이 많아", "일시적인 오류", "잠시 후 다시",
    "요청이 많아", "응답을 생성하지 못", "서비스에 문제가",
)

# 표지 기반 대체 경로에만 걸리는 상한. 확정 문구가 맞으면 길이는 보지 않는다.
# 긴 답변에 표지 두어 개가 우연히 들어가는 것을 막기 위한 것이다.
SERVICE_ERROR_MAX_CHARS = 400

# ---------------------------------------------------------------------------
# 입력 다듬기
# ---------------------------------------------------------------------------

# Step 1 에 넘길 이전 질문의 최대 개수.
# 대명사 해소에 필요한 것은 보통 직전 2~3턴이다. 그보다 오래된 질문은 노이즈에
# 가깝고 resolved_question 을 엉뚱한 주제로 끌고 갈 수 있다. 긴 대화에서는
# 입력 토큰도 턴 수에 비례해 늘어난다.
MAX_HISTORY_TURNS = 3

# 필터에서 "제한 없음"을 뜻하는 값들.
FILTER_ANY_VALUES = frozenset({"전체", "all", "ALL", "", "*"})

# ---------------------------------------------------------------------------
# 인용 검증  (사전지식 오염을 막는 핵심 임계값)
# ---------------------------------------------------------------------------

# 판정자가 근거로 제출한 인용의 최소 길이. 짧은 인용은 아무 문서에나 우연히
# 들어맞아 검증을 무력화한다.
EVIDENCE_MIN_QUOTE_CHARS = 8

# 완전 일치가 아니어도 통과시키는 최소 연속 일치 비율. 모델이 조사나 끝맺음을
# 살짝 다듬는 경우를 흡수하되, 문장을 새로 지어내면 통과하지 못하는 수준.
# 낮추면 지어낸 인용이 통과하기 시작한다.
MATCH_THRESHOLD = 0.9

# 답변이 인용부호로 제시한 문장을 원문과 대조할 때의 최소 길이 (case24).
# 위와 재는 대상이 다르다 - 이쪽은 답변이 주장한 인용, 위는 판정자가 낸 근거다.
ANSWER_QUOTE_MIN_CHARS = 10

# "짧게 답해줘"처럼 수치가 없는 요구를 판정하기 위한 기준값 (case11).
# 임의로 정한 값이라 실데이터로 보정해야 한다. 그때 LLM 을 다시 돌리지 않아도
# 되도록 판정 결과에 실제 측정값을 함께 남긴다.
VAGUE_SHORT_MAX_CHARS = 400

# ---------------------------------------------------------------------------
# 조직 분류
# ---------------------------------------------------------------------------

# 조직 분류 체계가 붙을 수 있는 로그 필드. 파일 이름으로 추측하지 않고 값을
# 대조해 고른다 - job_class 가 직무일 수도 직급일 수도 있고, 잘못 붙이면
# 에러 없이 전부 (미분류)가 되어 알아채기 어렵다.
ORG_CANDIDATE_FIELDS = ("db_dept_name", "db_job_name", "job_grade", "db_position_name")

# ---------------------------------------------------------------------------
